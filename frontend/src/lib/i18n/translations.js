/** Dot-path lookup with automatic fallback to English for any missing key -
 * this is what lets translation coverage roll out incrementally (e.g. a
 * newly-added string, or a lesson stage not yet translated) without ever
 * showing a blank or broken UI. */
export function getTranslation(language, path) {
  const dict = translations[language] || translations.en;
  const fallback = translations.en;
  const fromPath = (obj) => path.split('.').reduce((acc, key) => (acc == null ? acc : acc[key]), obj);
  const value = fromPath(dict);
  return value !== undefined ? value : fromPath(fallback);
}

/** Simple {placeholder} interpolation for the handful of dynamic strings
 * (plan names, child names, tier labels) - avoids pulling in a templating
 * library for what's otherwise a static dictionary. */
export function interpolate(str, vars) {
  if (typeof str !== 'string' || !vars) return str;
  return Object.entries(vars).reduce((acc, [key, val]) => acc.replaceAll(`{${key}}`, val), str);
}
